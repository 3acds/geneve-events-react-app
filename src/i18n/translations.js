export const normalizeLanguage = (value) => {
  if (typeof value !== 'string') return null;
  const primaryLanguage = value.trim().toLocaleLowerCase().split('-')[0];
  return LANGUAGE_OPTIONS.some(({ code }) => code === primaryLanguage)
    ? primaryLanguage
    : null;
};

const interpolate = (message, variables) => message.replace(
  /\{(\w+)\}/g,
  (placeholder, name) => (
    Object.prototype.hasOwnProperty.call(variables, name) ? variables[name] : placeholder
  ),
);

export const translateMessage = (language, key, variables = {}) => {
  const normalizedLanguage = normalizeLanguage(language) || DEFAULT_LANGUAGE;
  const message = TRANSLATIONS[normalizedLanguage]?.[key]
    ?? TRANSLATIONS[DEFAULT_LANGUAGE]?.[key];

  if (message == null) return key;
  const resolvedMessage = typeof message === 'function' ? message(variables) : message;
  return interpolate(String(resolvedMessage), variables);
};
